#!/usr/bin/env python3
"""Build the standalone Windhawk source; no includes of local files at runtime."""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
parts = {key: (ROOT / 'src' / f'{key}.cpp').read_text()
         for key in ('visibility', 'animation')}
includes = []
settings = []
seen = set()
bodies = []
for name, source in parts.items():
    for line in re.findall(r'^#include .+$', source, flags=re.M):
        if line not in includes:
            includes.append(line)
    block = source.split('// ==WindhawkModSettings==')[1].split('// ==/WindhawkModSettings==')[0]
    block = block.strip().removeprefix('/*').removesuffix('*/').strip()
    # Each setting is a top-level list item; oldTaskbarOnWin11 is shared.
    for entry in re.split(r'(?m)(?=^- [A-Za-z])', block):
        if not entry.strip():
            continue
        key = re.match(r'- ([A-Za-z0-9_]+):', entry).group(1)
        if key not in seen:
            seen.add(key)
            settings.append(entry.strip())
    body = source[source.index('#include'):]
    body = re.sub(r'^#include .+\n', '', body, flags=re.M)
    # Both implementations originally install the same LoadLibraryExW hook.
    # Replace them with one global dispatcher to avoid double-hooking in a mod.
    body, count = re.subn(
        r'    auto pKernelBaseLoadLibraryExW = .*?&LoadLibraryExW_Original\);\n',
        '', body, flags=re.S)
    assert count == 1, f'{name}: loader registration changed'
    body, count = re.subn(
        r'using LoadLibraryExW_t =.*?\n}\n', '', body, flags=re.S)
    assert count == 1, f'{name}: loader definition changed'
    if name == 'visibility':
        body = body.replace('    HMODULE kernelBaseModule = GetModuleHandle(L"kernelbase.dll");\n', '')
    for old, new in [('Wh_ModInit', 'Initialize'), ('Wh_ModAfterInit', 'AfterInitialize'),
                     ('Wh_ModUninit', 'Uninitialize'), ('Wh_ModSettingsChanged', 'SettingsChanged')]:
        body = re.sub(r'\b' + old + r'\b', new, body)
    # The host owns settings reload, not the component implementations.
    body, count = re.subn(r'BOOL SettingsChanged\(BOOL\* bReload\) \{.*?\n}\n?', '', body, flags=re.S)
    assert count == 1
    bodies.append(f'namespace {name} {{\n{body.strip()}\n}} // namespace {name}\n')

click_source = (ROOT / 'src/click-lock.cpp').read_text()
for line in re.findall(r'^#include .+$', click_source, flags=re.M):
    if line not in includes:
        includes.append(line)
click_body = re.sub(r'^#include .+\n', '', click_source, flags=re.M)
click_body = 'namespace click_lock {\n' + click_body + '\n} // namespace click_lock\n'

header = '''// ==WindhawkMod==
// @id              fluid-taskbar-auto-hide
// @name            Fluid taskbar auto-hide
// @description     Smooth taskbar animations with independent visibility controls for four displays
// @version         2.3.0
// @author          m417z (original mods), Fluid taskbar contributors
// @include         explorer.exe
// @architecture    x86-64
// @compilerOptions -DWINVER=0x0A00 -D_WIN32_WINNT=0x0A00 -ldwmapi -lole32 -loleaut32 -lruntimeobject -lversion -lwinmm
// ==/WindhawkMod==

// Original taskbar mods by m417z, licensed under GNU GPL v3.0.
// Derived from ramensoftware/windhawk-mods:
// mods/taskbar-auto-hide-speed.wh.cpp (1.1)
// mods/taskbar-auto-hide-when-maximized.wh.cpp (1.2.6)
// Local modifications: https://github.com/ironsensey/fluid-taskbar-auto-hide
// Generated by tools/build_single_file.py. Copy this entire file into Windhawk.

// ==WindhawkModReadme==
/*
# Fluid taskbar auto-hide

One mod for smooth animations and per-display adaptive visibility.
The taskbar stays visible with desktop/small windows and may auto-hide when
an app on the same display is maximized or fullscreen.

Four display toggles are always shown. Disconnected slots have no effect.
Slot 1 is primary; others are ordered by device name. Slots can change after
hotplugging. Native Windows 11 keeps its native animation curve; easing and FPS
settings customize the classic taskbar. Enable the old-taskbar setting only
when using ExplorerPatcher's classic taskbar.

Hidden shortcut: double-click empty taskbar space to keep that display's taskbar
revealed; repeat to release the lock and resume normal visibility rules.
There is no popup, sound, notification, or visible lock indicator. Locks reset
when the taskbar is recreated or the mod is reloaded/disabled.

Disable the previous Fluid animation/visibility companion mods and other
mods controlling the same behavior before enabling this combined mod.
Windows compilation and volume-flyout validation are still required.
*/
// ==/WindhawkModReadme==

// ==WindhawkModSettings==
/*
'''
footer = '''
namespace fluid {
using LoadLibraryExW_t = decltype(&LoadLibraryExW);
LoadLibraryExW_t originalLoadLibraryExW = nullptr;
bool visibilityInitialized = false;
bool animationInitialized = false;

HMODULE WINAPI LoadLibraryExW_Hook(LPCWSTR name, HANDLE file, DWORD flags) {
    HMODULE module = originalLoadLibraryExW(name, file, flags);
    if (module) {
        visibility::HandleLoadedModuleIfExplorerPatcher(module);
        visibility::HandleLoadedModuleIfTaskbarView(module, name);
        animation::HandleLoadedModuleIfExplorerPatcher(module);
        animation::HandleLoadedModuleIfTaskbarView(module, name);
    }
    return module;
}
} // namespace fluid

BOOL Wh_ModInit() {
    // Register the one shared loader hook before component hooks. Windhawk
    // activates registered hooks after initialization completes.
    HMODULE kernelBase = GetModuleHandleW(L"kernelbase.dll");
    if (!kernelBase) return FALSE;
    auto loader = reinterpret_cast<decltype(&LoadLibraryExW)>(
        GetProcAddress(kernelBase, "LoadLibraryExW"));
    if (!loader || !WindhawkUtils::Wh_SetFunctionHookT(
            loader, fluid::LoadLibraryExW_Hook, &fluid::originalLoadLibraryExW)) {
        return FALSE;
    }
    if (!visibility::Initialize()) return FALSE;
    fluid::visibilityInitialized = true;
    if (!animation::Initialize()) {
        visibility::Uninitialize();
        fluid::visibilityInitialized = false;
        return FALSE;
    }
    fluid::animationInitialized = true;
    if (!click_lock::Start()) {
        animation::Uninitialize();
        fluid::animationInitialized = false;
        visibility::Uninitialize();
        fluid::visibilityInitialized = false;
        return FALSE;
    }
    return TRUE;
}

void Wh_ModAfterInit() {
    visibility::AfterInitialize();
    animation::AfterInitialize();
}

void Wh_ModUninit() {
    click_lock::Stop();
    if (fluid::animationInitialized) {
        animation::Uninitialize();
        fluid::animationInitialized = false;
    }
    if (fluid::visibilityInitialized) {
        visibility::Uninitialize();
        fluid::visibilityInitialized = false;
    }
}

BOOL Wh_ModSettingsChanged(BOOL* reload) {
    // One reload updates both components without concurrent settings mutation.
    *reload = TRUE;
    return TRUE;
}
'''
output = (header + '\n'.join(settings) + '\n*/\n// ==/WindhawkModSettings==\n\n' +
          '\n'.join(includes) + '\n\n' + (ROOT / 'src/runtime-state.inc').read_text() + '\n' +
          click_body + '\n' + '\n'.join(bodies) + footer)
target = ROOT / 'fluid-taskbar-auto-hide.wh.cpp'
if '--check' in sys.argv:
    assert target.read_text() == output, 'Regenerate fluid-taskbar-auto-hide.wh.cpp'
    print('Standalone mod matches component sources')
else:
    target.write_text(output)
    print('Generated', target.name)
